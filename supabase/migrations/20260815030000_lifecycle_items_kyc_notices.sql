-- =============================================================================
-- Stage 2: one consolidated schema migration.
--   * loan lifecycle: loan_status enum, redemption audit columns, renewals
--   * pledged items: loan_items (integer milligrams) + loan_item_photos
--   * KYC on profiles + a private 'kyc' bucket
--   * notices: loan_notices + server-side loans_overdue_as_of()
--
-- Owner decisions recorded here so the reasoning is not lost:
--   * Existing status='closed' rows STAY 'closed'. 'closed' now means "ended,
--     redemption details unknown" (they predate the audit columns); 'redeemed'
--     is reserved for rows written by the Stage 3 redemption RPC, which always
--     records redeemed_on/redeemed_by/closure_balance_paise.
--   * Item photos reuse the existing private 'receipts' bucket under
--     {customer_id}/items/... The five receipts_* policies already require a
--     UUID first path segment and do not constrain the second, so this needs no
--     new storage policy. A separate bucket would have duplicated all five.
--   * NO Aadhaar images are stored, at any time, enforced by a CHECK. UIDAI's
--     Do's and Don'ts for requesting entities forbid storing a photocopy of an
--     Aadhaar letter without redacting the first 8 digits, and this shop has no
--     masking pipeline or Aadhaar Data Vault. last4 is kept for all document
--     types; document images are allowed for pan/voter_id/driving_licence/
--     passport only.
--   * The walk-in blocker is solved OUTSIDE the schema, by an Edge Function
--     calling auth.admin.createUser({ phone, phone_confirm: true }). That keeps
--     profiles.id = auth.uid(), so no RLS policy or storage path changes here.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. Loan lifecycle: status becomes a real enum
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'loan_status') THEN
    CREATE TYPE public.loan_status AS ENUM ('active', 'redeemed', 'closed', 'defaulted');
  END IF;
END $$;

-- The baseline declared status with an INLINE unnamed CHECK, so its name was
-- generated by Postgres. Resolve it from the catalog rather than guessing.
DO $$
DECLARE
  v_conname text;
BEGIN
  FOR v_conname IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public.loans'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%status%'
  LOOP
    EXECUTE format('ALTER TABLE public.loans DROP CONSTRAINT %I', v_conname);
  END LOOP;
END $$;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'loans'
      AND column_name = 'status' AND data_type = 'text'
  ) THEN
    -- A text default cannot be cast implicitly during the type change.
    ALTER TABLE public.loans ALTER COLUMN status DROP DEFAULT;
    -- Both live values ('active','closed') are labels of the new enum, so a
    -- plain cast is exact. Anything else raises, which is the honest outcome.
    ALTER TABLE public.loans
      ALTER COLUMN status TYPE public.loan_status
      USING status::public.loan_status;
    ALTER TABLE public.loans
      ALTER COLUMN status SET DEFAULT 'active'::public.loan_status;
  END IF;
END $$;

ALTER TABLE public.loans
  ADD COLUMN IF NOT EXISTS redeemed_on date,
  ADD COLUMN IF NOT EXISTS redeemed_by uuid REFERENCES public.profiles (id) ON DELETE RESTRICT,
  ADD COLUMN IF NOT EXISTS released_to_name text,
  ADD COLUMN IF NOT EXISTS release_note text,
  ADD COLUMN IF NOT EXISTS closure_balance_paise bigint;

COMMENT ON COLUMN public.loans.closure_balance_paise IS
  'Total due at the moment of redemption. Immutable audit figure: a later rate '
  'or term edit must never be able to rewrite what was actually collected.';

ALTER TABLE public.loans
  DROP CONSTRAINT IF EXISTS loans_closure_balance_chk;
ALTER TABLE public.loans
  ADD CONSTRAINT loans_closure_balance_chk
  CHECK (closure_balance_paise IS NULL OR closure_balance_paise >= 0);

-- A redeemed loan must carry its audit snapshot. Legacy 'closed' rows are
-- deliberately exempt: they were closed before these columns existed.
ALTER TABLE public.loans
  DROP CONSTRAINT IF EXISTS loans_redeemed_audit_chk;
ALTER TABLE public.loans
  ADD CONSTRAINT loans_redeemed_audit_chk CHECK (
    status <> 'redeemed'::public.loan_status
    OR (redeemed_on IS NOT NULL AND closure_balance_paise IS NOT NULL)
  );

COMMENT ON COLUMN public.loans.item_name IS
  'DEPRECATED: superseded by public.loan_items. Retained because the admin UI '
  'still reads it. Drop in a later migration once the UI is migrated.';
COMMENT ON COLUMN public.loans.weight_grams IS
  'DEPRECATED: numeric(10,3) float-adjacent liability. Use '
  'public.loan_items.gross_weight_mg / net_weight_mg (integer milligrams).';

