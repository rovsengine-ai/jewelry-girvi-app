-- 4. Pledged items — integer milligrams, one row per ornament
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.loan_items (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- CASCADE: an item has no meaning without its loan, and only an owner can
  -- delete a loan in the first place (loans_owner_delete + the trigger above).
  loan_id             uuid NOT NULL REFERENCES public.loans (id) ON DELETE CASCADE,
  ornament_type       text NOT NULL,
  description         text,
  gross_weight_mg     bigint NOT NULL,
  net_weight_mg       bigint NOT NULL,
  purity_karat        smallint,
  stone_deduction_mg  bigint NOT NULL DEFAULT 0,
  quantity            smallint NOT NULL DEFAULT 1,
  valuation_paise     bigint,
  created_at          timestamptz NOT NULL DEFAULT timezone('utc', now()),

  CONSTRAINT loan_items_gross_weight_chk CHECK (gross_weight_mg > 0),
  CONSTRAINT loan_items_net_weight_chk CHECK (net_weight_mg > 0),
  CONSTRAINT loan_items_net_not_over_gross_chk CHECK (net_weight_mg <= gross_weight_mg),
  CONSTRAINT loan_items_stone_deduction_chk CHECK (stone_deduction_mg >= 0),
  CONSTRAINT loan_items_purity_karat_chk CHECK (
    purity_karat IS NULL OR (purity_karat BETWEEN 1 AND 24)
  ),
  CONSTRAINT loan_items_quantity_chk CHECK (quantity >= 1),
  CONSTRAINT loan_items_valuation_chk CHECK (valuation_paise IS NULL OR valuation_paise >= 0)
);

COMMENT ON COLUMN public.loan_items.purity_karat IS
  'NULL means not assessed. Never default this to 22 — an assumed purity would '
  'flow into valuation and misprice the pledge.';

