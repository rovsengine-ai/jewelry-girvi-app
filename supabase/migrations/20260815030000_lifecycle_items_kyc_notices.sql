-- Overdue determination is server-side. Never compare dates in JavaScript.
-- SECURITY INVOKER, so RLS decides the rows: shop users see every overdue loan,
-- a customer sees only their own.
CREATE OR REPLACE FUNCTION public.loans_overdue_as_of(
  p_as_of date DEFAULT ((timezone('Asia/Kolkata', now()))::date)
)
RETURNS TABLE (
  loan_id                      uuid,
  customer_id                  uuid,
  serial_number                text,
  disbursed_on                 date,
  due_on                       date,
  days_overdue                 integer,
  outstanding_principal_paise  bigint,
  accrued_interest_paise       bigint,
  total_due_paise              bigint
)
LANGUAGE sql
STABLE
SECURITY INVOKER
AS $$
  SELECT
    l.id,
    l.customer_id,
    l.serial_number,
    l.disbursed_on,
    (l.disbursed_on + l.simple_period_days)::date,
    (p_as_of - (l.disbursed_on + l.simple_period_days))::integer,
    b.outstanding_principal_paise,
    b.accrued_interest_paise,
    b.total_due_paise
  FROM public.loans l
  CROSS JOIN LATERAL public.loan_balances_as_of(l.id, p_as_of) b
  WHERE l.status = 'active'::public.loan_status
    AND p_as_of > (l.disbursed_on + l.simple_period_days)
  ORDER BY (l.disbursed_on + l.simple_period_days) ASC;
$$;

